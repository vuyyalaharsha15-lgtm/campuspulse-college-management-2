-- PostgreSQL schema for CampusPulse. Apply only to a fresh Supabase project.
-- Existing tables are not dropped. If you already created the tables in Supabase,
-- compare this schema with the live tables before running any changes.
CREATE TABLE IF NOT EXISTS public.students (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(100) NOT NULL, email varchar(100) NOT NULL UNIQUE,
 student_id varchar(20) NOT NULL UNIQUE, department varchar(50), phone varchar(15),
 password varchar(255) NOT NULL, created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
 otp varchar(6), email_verified boolean NOT NULL DEFAULT false, otp_expires_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.admins (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username varchar(50) UNIQUE,
 email varchar(100), password varchar(255)
);
CREATE TABLE IF NOT EXISTS public.coordinators (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100),
 email varchar(100) UNIQUE, department varchar(50), password varchar(255)
);
CREATE TABLE IF NOT EXISTS public.events (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title varchar(100), description text,
 category varchar(50), venue varchar(100), event_date date, event_time time,
 coordinator_id integer, max_participants integer, status varchar(20) DEFAULT 'Open',
 created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP, fee numeric(10,2) DEFAULT 0.00
);
CREATE TABLE IF NOT EXISTS public.registrations (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id integer REFERENCES public.students(id),
 event_id integer REFERENCES public.events(id), registration_date timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
 status varchar(20) DEFAULT 'Registered'
);
CREATE TABLE IF NOT EXISTS public.attendance (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id integer NOT NULL REFERENCES public.students(id),
 event_id integer NOT NULL REFERENCES public.events(id), status varchar(10) DEFAULT 'Absent' CHECK (status IN ('Present','Absent')),
 marked_on timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.certificates (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id integer REFERENCES public.students(id),
 event_id integer REFERENCES public.events(id), certificate_no varchar(100), issue_date date
);
CREATE TABLE IF NOT EXISTS public.feedback (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id integer REFERENCES public.students(id),
 event_id integer REFERENCES public.events(id), rating integer, comments text,
 created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.payments (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id integer NOT NULL REFERENCES public.students(id),
 event_id integer NOT NULL REFERENCES public.events(id), amount numeric(10,2),
 payment_status varchar(20) DEFAULT 'Pending', transaction_id varchar(100),
 payment_date timestamp without time zone DEFAULT CURRENT_TIMESTAMP, payment_mode varchar(20) DEFAULT 'UPI',
 verified boolean DEFAULT false, receipt_generated boolean DEFAULT false
);
